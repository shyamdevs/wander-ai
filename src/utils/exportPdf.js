import { buildSchedule, stopMinutes } from "./schedule";
import { fmtDuration, fmtTime } from "./geo";
import { dayDate, fmtDate } from "./dates";
import { money } from "./format";

const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

const CSS = `body{font:14px/1.5 -apple-system,"Segoe UI",Roboto,sans-serif;color:#111;max-width:760px;margin:32px auto;padding:0 24px}
h1{font-size:26px;margin:0 0 4px}h2{font-size:17px;margin:28px 0 8px;border-bottom:2px solid #111;padding-bottom:4px}
.m{color:#555;font-size:12px}table{width:100%;border-collapse:collapse;margin-top:6px}td,th{padding:6px 8px;border-bottom:1px solid #ddd;text-align:left;vertical-align:top;font-size:13px}
th{font-size:11px;text-transform:uppercase;color:#666}.r{text-align:right;white-space:nowrap}tr{page-break-inside:avoid}.note{margin-top:28px;font-size:11px;color:#666}`;

// Opens a clean printable page; the browser's "Save as PDF" turns it into a PDF.
// Returns false if the pop-up was blocked.
export function exportTripPdf(plan) {
  const w = window.open("", "_blank");
  if (!w) return false;
  const c = plan.currency;
  const people = plan.travelers || 1;

  const budget = ["transport", "stay", "food", "activities"]
    .map((k) => `<tr><td>${{ transport: "Travel", stay: "Stay", food: "Food &amp; dining", activities: "Activities &amp; entry fees" }[k]}</td><td class="r">${esc(money(plan.breakdown[k].amount, c))}</td></tr>`)
    .join("");

  const days = plan.itinerary.map((d) => {
    const sched = buildSchedule(d.stops);
    const date = dayDate(plan.startDate, d.day);
    const rows = d.stops.map((s, i) => `<tr><td class="r">${fmtTime(sched[i].arrive)}</td><td><b>${esc(s.name)}</b><br><span class="m">${esc(s.description)}</span></td><td class="r">${fmtDuration(stopMinutes(s))}</td><td class="r">${Number(s.estimatedCost) > 0 ? `~${esc(money(s.estimatedCost, c))} est.` : "Free entry"}</td></tr>`).join("");
    return `<h2>Day ${d.day}${date ? ` · ${esc(fmtDate(date))}` : ""} — ${esc(d.title)}</h2><table><tr><th class="r">Arrive</th><th>Place</th><th class="r">Stay</th><th class="r">Est. cost</th></tr>${rows}</table>`;
  }).join("");

  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(plan.title)}</title><style>${CSS}</style></head><body>
<h1>${esc(plan.title)}</h1>
<p class="m">${esc(plan.destination)} · ${plan.durationDays} days · ${people} traveler${people > 1 ? "s" : ""}${plan.startDate ? ` · starts ${esc(plan.startDate)}` : ""}</p>
<p>${esc(plan.summary)}</p>
<h2>Budget (AI estimates)</h2><table>${budget}
<tr><td><b>Total planned</b></td><td class="r"><b>${esc(money(plan.totalEstimated, c))}</b></td></tr>
<tr><td>Your budget</td><td class="r">${esc(money(plan.totalBudget, c))}</td></tr>
<tr><td>Per person</td><td class="r">${esc(money(plan.totalEstimated / people, c))}</td></tr></table>
${days}
<p class="note">Generated by Wander AI. Times assume a 9:00 AM start and use straight-line travel estimates. Stop costs are indicative AI/budget-based estimates, not official venue tariffs. Confirm entry fees, meal and hotel prices before you go.</p>
</body></html>`);
  w.document.close();
  w.focus();
  setTimeout(() => w.print(), 400);
  return true;
}
